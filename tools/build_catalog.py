"""Regenerate CATALOG.md from the metadata.json files in structures/."""

from library import ROOT, find_entries, load_atoms, load_metadata


def short_reference(meta: dict) -> str:
    if meta.get("source_type") == "generated":
        return "Generated in this repository"
    if meta.get("source_type") == "own-calculation":
        return "Own calculation"
    ref = meta.get("reference") or {}
    if not ref:
        return "n/a"
    first_author = ref["authors"].split(",")[0].split(" and ")[0].strip()
    text = f"{first_author} et al., {ref['journal']} ({ref['year']})"
    return f"[{text}](https://doi.org/{ref['doi']})"


def main() -> None:
    rows = []
    for entry in find_entries():
        meta = load_metadata(entry)
        atoms = load_atoms(entry)
        a, b, c = atoms.cell.lengths()
        rel = entry.relative_to(ROOT).as_posix()
        rows.append(
            f"| [{meta['name']}]({rel}) | {atoms.get_chemical_formula()} | {len(atoms)} "
            f"| {a:.2f} x {b:.2f} x {c:.2f} | {meta['category']} | {short_reference(meta)} |"
        )

    header = (
        "# Structure catalog\n\n"
        "This file is generated by `tools/build_catalog.py`. Do not edit it by hand.\n\n"
        "| Structure | Formula | Atoms | Cell (Angstrom) | Category | Source |\n"
        "|---|---|---|---|---|---|\n"
    )
    (ROOT / "CATALOG.md").write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"Wrote CATALOG.md with {len(rows)} structure(s).")


if __name__ == "__main__":
    main()
